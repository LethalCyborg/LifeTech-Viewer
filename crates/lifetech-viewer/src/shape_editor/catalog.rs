#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn catalogue_matches_the_shipped_tweakable_shape_parameters() {
        let xml = lifetech_llsd::xml::parse(include_bytes!("../../assets/character/avatar_lad.xml")).expect("LAD");
        let mut ids = std::collections::BTreeSet::new();
        let mut stack = vec![&xml];
        while let Some(el) = stack.pop() {
            if el.name == "param"
                && el.attr("wearable") == Some("shape")
                && matches!(el.attr("group"), None | Some("0") | Some("3"))
                && el.attr("edit_group").is_some_and(|g| g.starts_with("shape_"))
            {
                let id = el.attr("id").expect("id").parse::<i32>().expect("id");
                if !ids.insert(id) {
                    continue;
                }
                let p = PARAMS.iter().find(|p| p.id == id).expect("shape control");
                assert_eq!(p.min, el.attr("value_min").unwrap_or("0").parse::<f32>().expect("minimum"));
                assert_eq!(p.max, el.attr("value_max").unwrap_or("1").parse::<f32>().expect("maximum"));
            }
            stack.extend(el.elements().collect::<Vec<_>>().into_iter().rev());
        }
        assert_eq!(ids.len(), PARAMS.len());
        assert!(ids.contains(&33));
        assert!(ids.contains(&11001));
    }
}
